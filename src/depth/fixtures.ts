/** A checker floor receding to a horizon with lit spheres standing on it. */
function drawSynthetic() {
  const W = 960, H = 640, horizon = H * 0.34, image = createCanvas(W, H), g = get2d(image, true);
  const truth = new Float32Array(W * H);
  const img = g.createImageData(W, H), d = img.data;
  const spheres = [{ x: -1.5, z: 3, r: 0.6, c: [214, 72, 60] }, { x: 1.3, z: 5, r: 0.9, c: [60, 130, 220] }, { x: -0.2, z: 9, r: 1.1, c: [230, 190, 70] }];
  const f = 620, cam = 1.6;
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const i = (y * W + x) * 4, dx = (x - W / 2) / f, dy = (y - horizon) / f, n = Math.hypot(dx, dy, 1);
      const rd = [dx / n, dy / n, 1 / n];
      let t = Infinity, col = [150, 190, 235 - (y / H) * 30], hit = -1;
      if (rd[1] > 1e-4) {
        const tp = cam / rd[1], px = rd[0] * tp, pz = rd[2] * tp;
        if (tp < 200) { t = tp; const c = (Math.floor(px) + Math.floor(pz)) & 1, fade = Math.min(1, 7 / pz); col = (c ? [205, 200, 188] : [84, 88, 92]).map((v) => v * fade + 170 * (1 - fade)); }
      }
      spheres.forEach((s, k) => {
        const oc = [-s.x, -cam + s.r * 0 + cam - (cam - s.r), -s.z], b = oc[0] * rd[0] + oc[1] * rd[1] + oc[2] * rd[2], c = oc[0] ** 2 + oc[1] ** 2 + oc[2] ** 2 - s.r ** 2, q = b * b - c;
        if (q > 0) { const ts = -b - Math.sqrt(q); if (ts > 0 && ts < t) { t = ts; hit = k; } }
      });
      if (hit >= 0) {
        const s = spheres[hit], p = [rd[0] * t - s.x, rd[1] * t - (cam - s.r), rd[2] * t - s.z].map((v) => v / s.r), l = Math.max(0.15, p[0] * -0.5 + p[1] * -0.7 + p[2] * -0.5);
        col = s.c.map((v) => Math.min(255, v * l + 90 * l ** 12));
      }
      d[i] = col[0]; d[i + 1] = col[1]; d[i + 2] = col[2]; d[i + 3] = 255;
      truth[y * W + x] = Number.isFinite(t) ? 1 / t : 0;
    }
  g.putImageData(img, 0, 0);
  return { image, truth };
}
